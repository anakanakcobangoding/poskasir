import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

test('POS topping controls, cart, checkout payload, limits, and modal reset in Chrome', () => {
    const source = readFileSync(new URL('../resources/js/app.js', import.meta.url), 'utf8');
    const ids = [...new Set([...source.matchAll(/getElementById\('([^']+)'\)/g)].map((match) => match[1]))];
    const dialogs = ['pos-discount-dialog', 'pos-fee-dialog', 'pos-topping-modal', 'pos-checkout-step1', 'pos-checkout-step2', 'pos-checkout-step3', 'pos-checkout-qris'];
    const html = ids.map((id) => {
        const tag = id === 'pos-qris-image' ? 'img' : dialogs.includes(id) ? 'dialog' : id === 'pos-order-form' ? 'form' : /amount|search|customer|notes|table|confirmed/.test(id) ? 'input' : 'div';
        return `<${tag} id="${id}"></${tag}>`;
    }).join('') + '<button data-discount-save></button><button data-discount-cancel></button><button data-discount-remove></button><button data-fee-save></button><button data-fee-cancel></button><button data-fee-remove></button>';
    const checks = `
        const check = (condition, message) => { if (!condition) throw new Error(message); };
        const el = (id) => document.getElementById(id);
        const click = (selector) => document.querySelector(selector).click();
        const qr = el('pos-qris-image');
        qr.src = 'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';
        await qr.decode();
        await new Promise((resolve) => setTimeout(resolve, 0));
        check(qr.naturalWidth === 1 && !qr.hidden && !el('pos-qris-submit').disabled, 'Loaded QR image must display and enable confirmation');
        qr.src = 'data:image/gif;base64,invalid';
        await new Promise((resolve) => qr.addEventListener('error', resolve, { once: true }));
        check(qr.hidden && !el('pos-qris-retry').hidden && el('pos-qris-submit').disabled, 'Failed QR load must offer retry and block completion');
        click('#pos-qris-retry');
        check(!el('pos-qris-loading').hidden && el('pos-qris-submit').disabled, 'QR retry must show loading');
        const quantity = (id) => document.querySelector('.js-modal-topping-qty[data-topping-id="' + id + '"]').textContent;
        const select = (id) => click('.js-modal-topping-qty-plus[data-topping-id="' + id + '"]');
        click('.js-product');
        select(1);
        check(quantity(1) === '1', 'Selected topping must display 1');
        click('.js-modal-topping-qty-plus[data-topping-id="1"]');
        click('.js-modal-topping-qty-plus[data-topping-id="1"]');
        check(quantity(1) === '3', 'Each click must increase the visible quantity');
        select(2);
        check(quantity(2) === '1' && quantity(1) === '3', 'Topping quantities must be independent');
        click('.js-modal-topping-qty-minus[data-topping-id="2"]');
        check(quantity(2) === '0', 'Zero quantity must remove the topping');
        for (let i = 0; i < 25; i++) click('.js-modal-topping-qty-plus[data-topping-id="2"]');
        check(quantity(2) === '20', 'Topping maximum must stay 20');
        for (let i = 0; i < 18; i++) click('.js-modal-topping-qty-minus[data-topping-id="2"]');
        check(quantity(2) === '2', 'Minus must update visible quantity');
        check(el('pos-modal-qty').textContent === '1', 'Topping controls must not change product quantity');
        click('#pos-modal-qty-plus');
        check(el('pos-modal-total').textContent.replace(/\\D/g, '') === '46000', 'Modal total must include independent topping quantities');
        click('#pos-modal-add');
        check(el('pos-total').textContent.replace(/\\D/g, '') === '46000', 'Cart total must match modal');
        click('#pos-discount-open');
        el('pos-discount-type').value = 'fixed'; el('pos-discount-value').value = '999999'; click('[data-discount-save]');
        check(!el('pos-discount-error').hidden, 'Discount above subtotal must be rejected');
        el('pos-discount-value').value = '5000'; click('[data-discount-save]');
        check(el('pos-total').textContent.replace(/\\D/g, '') === '41000', 'Fixed discount must reduce final total');
        click('#pos-fee-open'); el('pos-fee-name').value = 'Tip'; el('pos-fee-value-input').value = '2000'; click('[data-fee-save]');
        check(el('pos-total').textContent.replace(/\\D/g, '') === '43000', 'Additional fee must be added after discount');
        click('#pos-discount-open'); el('pos-discount-type').value = 'percentage'; el('pos-discount-value').value = '10'; click('[data-discount-save]');
        check(el('pos-total').textContent.replace(/\\D/g, '') === '43400', 'Percentage discount must use product and topping subtotal before fees');
        check(el('pos-topping-total').textContent.replace(/\\D/g, '') === '26000', 'Topping subtotal must include product quantity');
        check(el('pos-cart-lines').textContent.includes('Telur x3, Keju x2'), 'Cart topping labels must match quantities');
        check(el('pos-cart-lines').querySelector('img[data-cart-image]')?.getAttribute('src') === 'product.png', 'Cart must retain the real product image URL');
        click('.js-product');
        check(quantity(1) === '0' && quantity(2) === '0', 'New product configuration must reset topping selections');
        click('.js-modal-topping-qty-plus[data-topping-id="1"]');
        check(quantity(1) === '1', 'Reopening modal must not multiply click handlers');
        click('#pos-modal-close');
        click('#pos-checkout'); click('#pos-step1-next'); click('#pos-step2-next');
        click('.pos-payment-method-btn');
        el('pos-step3-amount').value = '50000';
        click('#pos-step3-pay-cash');
        check(window.payload.items[0].quantity === 2, 'Checkout product quantity must be 2');
        check(window.payload.items[0].toppings[0].quantity === 3 && window.payload.items[0].toppings[1].quantity === 2, 'Checkout topping quantities must match modal');
        check(window.payload.payment_method === 'cash', 'Cash checkout must still submit');
        check(window.payload.discount_type === 'percentage' && window.payload.discount_value === 10, 'Percentage discount must reach checkout payload');
        check(window.payload.additional_fee_label === 'Tip' && window.payload.additional_fee_amount === 2000, 'Fee must reach checkout payload');
        const firstKey = window.requestHeaders['Idempotency-Key'];
        check(typeof firstKey === 'string' && firstKey.length === 36, 'Checkout must send an idempotency UUID');
        await new Promise((resolve) => setTimeout(resolve, 0));
        document.querySelectorAll('dialog[open]').forEach((dialog) => dialog.close());
        click('#pos-checkout'); click('#pos-step1-next'); click('#pos-step2-next'); click('.pos-payment-method-btn');
        el('pos-step3-amount').value = '50000'; click('#pos-step3-pay-cash');
        check(window.requestHeaders['Idempotency-Key'] === firstKey, 'Reopening the same cart after a failed response must reuse the checkout key');
        el('results').textContent = 'PASS';
    `;
    const directory = mkdtempSync(join(tmpdir(), 'pos-browser-'));
    try {
        const file = join(directory, 'test.html');
        writeFileSync(file, `<!doctype html><meta charset="utf-8">${html}<button class="js-product" data-id="1" data-name="Product" data-price="10000" data-search="product"></button><button class="pos-payment-method-btn" data-method="cash"></button><pre id="results">NOT RUN</pre><script>window.posToppings=[{id:1,name:'Telur',price:3000},{id:2,name:'Keju',price:2000}];window.posProductImages={'1':'product.png'};window.posProductToppings={'1':[1,2]};window.fetch=async(url,options)=>{window.payload=JSON.parse(options.body);window.requestHeaders=options.headers;return {ok:false,json:async()=>({message:'test response'})}};</script><script>${source}</script><script>(async () => { try { ${checks} } catch(error) { document.getElementById('results').textContent = error.stack; } })();</script>`);
        const output = execFileSync(process.env.CHROME_BIN ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless', '--no-first-run', '--no-default-browser-check', `--user-data-dir=${join(directory, 'profile')}`, '--dump-dom', '--virtual-time-budget=1000', `file://${file}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 30000 });
        const result = output.match(/<pre id="results">([\s\S]*?)<\/pre>/)?.[1];
        assert.equal(result, 'PASS');
    } finally {
        rmSync(directory, { recursive: true, force: true });
    }
});
